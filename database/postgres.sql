CREATE TABLE petugas (
    id_petugas integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_petugas varchar(100) NOT NULL,
    role_petugas varchar(30) NOT NULL CHECK(role_petugas IN ('Admin','Inbound Checker','Outbound Sorter')),
    no_telepon varchar(20) NOT NULL
);
CREATE TABLE rak_gudang (
    id_rak integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_rak varchar(20) NOT NULL UNIQUE,
    zona varchar(20) NOT NULL,
    kapasitas_maks_kg numeric(6,2) NOT NULL,
    kapasitas_terpakai_kg numeric(6,2) NOT NULL DEFAULT 0
);
CREATE TABLE paket (
    no_resi varchar(30) PRIMARY KEY,
    nama_pengirim varchar(100) NOT NULL,
    nama_penerima varchar(100) NOT NULL,
    kota_tujuan varchar(50) NOT NULL,
    berat_kg numeric(6,2) NOT NULL,
    kategori varchar(50) NOT NULL,
    status_paket varchar(20) NOT NULL DEFAULT 'Diterima' CHECK(status_paket IN ('Diterima','Tersimpan','Siap Kirim','Terkirim'))
);
CREATE TABLE alokasi_rak (
    id_alokasi integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_resi varchar(30) NOT NULL REFERENCES paket(no_resi) ON UPDATE CASCADE,
    id_rak integer NOT NULL REFERENCES rak_gudang(id_rak) ON UPDATE CASCADE,
    id_petugas integer NOT NULL REFERENCES petugas(id_petugas) ON UPDATE CASCADE,
    waktu_masuk timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_alokasi varchar(20) NOT NULL DEFAULT 'Aktif' CHECK(status_alokasi IN ('Aktif','Selesai'))
);
CREATE TABLE pengiriman (
    id_pengiriman integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_resi varchar(30) NOT NULL UNIQUE REFERENCES paket(no_resi) ON UPDATE CASCADE,
    id_petugas integer NOT NULL REFERENCES petugas(id_petugas) ON UPDATE CASCADE,
    nama_kurir varchar(100) NOT NULL,
    no_kendaraan varchar(20) NOT NULL,
    waktu_kirim timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_kirim varchar(30) NOT NULL DEFAULT 'Dalam Perjalanan' CHECK(status_kirim IN ('Dalam Perjalanan','Terkirim','Selesai'))
);
CREATE INDEX alokasi_rak_paket_idx ON alokasi_rak(no_resi);
CREATE INDEX alokasi_rak_rak_idx ON alokasi_rak(id_rak);
CREATE INDEX alokasi_rak_petugas_idx ON alokasi_rak(id_petugas);
CREATE INDEX pengiriman_petugas_idx ON pengiriman(id_petugas);
CREATE SCHEMA app_runtime;
CREATE TABLE app_runtime.sessions(id varchar(128) PRIMARY KEY, data text NOT NULL, expires_at timestamptz NOT NULL);
CREATE INDEX sessions_expiry_idx ON app_runtime.sessions(expires_at);
